#!/usr/bin/env node

import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(repoRoot, "assets", "icon.png");
const outputPath = join(repoRoot, "worker", "src", "connector-icon-assets.js");
const temporaryDirectory = await mkdtemp(join(tmpdir(), "wave-connector-icons-"));

const variants = [16, 32, 48, 64, 96, 128, 256].map((size) => ({
  name: `CONNECTOR_FAVICON_${size}_PNG`,
  filename: `favicon-${size}x${size}.png`,
  size,
}));
variants.push({ name: "CONNECTOR_APPLE_TOUCH_ICON_PNG", filename: "apple-touch-icon.png", size: 180 });

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function exportedAsset(name, buffer) {
  return `export const ${name}_SHA256 = "${sha256(buffer)}";\n` +
    `const ${name}_BASE64 = "${buffer.toString("base64")}";\n` +
    `export const ${name} = decodeBase64(${name}_BASE64);\n`;
}

try {
  const source = await readFile(sourcePath);
  const generated = [];

  for (const variant of variants) {
    const generatedPath = join(temporaryDirectory, variant.filename);
    await execFileAsync("magick", [
      sourcePath,
      "-strip",
      "-depth",
      "8",
      "-resize",
      `${variant.size}x${variant.size}`,
      "-define",
      "png:exclude-chunks=date,time",
      "-define",
      "png:color-type=6",
      generatedPath,
    ]);
    generated.push({ name: variant.name, buffer: await readFile(generatedPath) });
  }

  // A single 32x32 frame. The six-frame variant (16,32,48,64,128,256) produced
  // an uncompressed 370 KB ICO, which is large enough that icon resolvers give
  // up rather than decode it. sosumi.ai, whose connector icon does render in
  // Claude, serves exactly one 32x32 frame at 4,286 bytes. See WORKLOG
  // 2026-07-30.
  const faviconPath = join(temporaryDirectory, "favicon.ico");
  await execFileAsync("magick", [
    sourcePath,
    "-strip",
    "-define",
    "icon:auto-resize=32",
    faviconPath,
  ]);
  generated.push({ name: "CONNECTOR_FAVICON_ICO", buffer: await readFile(faviconPath) });

  // Wave's icon is raster-only, so /favicon.svg wraps the 96px PNG rather than
  // being true vector art. Resolvers that ask for an SVG favicon first still
  // get the correct logo, and the wrapper stays a few kilobytes.
  const faviconSvgPng = generated.find(
    ({ name }) => name === "CONNECTOR_FAVICON_96_PNG",
  );
  if (!faviconSvgPng) throw new Error("Expected the 96px PNG variant to be generated first.");
  const faviconSvg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="96" height="96">' +
    `<image href="data:image/png;base64,${faviconSvgPng.buffer.toString("base64")}" ` +
    'width="96" height="96"/></svg>';
  generated.push({
    name: "CONNECTOR_FAVICON_SVG",
    buffer: Buffer.from(faviconSvg, "utf8"),
  });

  const output = [
    "// Generated by scripts/generate-worker-icon-assets.mjs.",
    "// Canonical source: assets/icon.png.",
    "// Run `npm run build:worker-icons` after changing the canonical icon.",
    "",
    "function decodeBase64(value) {",
    "  return Uint8Array.from(atob(value), (character) => character.charCodeAt(0));",
    "}",
    "",
    exportedAsset("CONNECTOR_ICON_PNG", source),
    ...generated.map(({ name, buffer }) => exportedAsset(name, buffer)),
  ].join("\n");

  await writeFile(outputPath, output);
  console.log(`Generated ${outputPath} from ${sourcePath}`);
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true });
}
